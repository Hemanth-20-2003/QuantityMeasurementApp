// Convert using factor
function convert(value, factor) {
  return value * factor;
}

// Compare values
function compare(a, b) {
  if (a > b) return "greater";
  if (a < b) return "smaller";
  return "equal";
}

// Add/Subtract values
function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}